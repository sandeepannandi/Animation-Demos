import base64, io, json
from PIL import Image

COLS, ROWS = 64, 44
META = [
    ("starry-night",  "The Starry Night",        "Vincent van Gogh",  "1889"),
    ("great-wave",    "The Great Wave off Kanagawa", "Katsushika Hokusai", "c. 1831"),
    ("pearl-earring", "Girl with a Pearl Earring", "Johannes Vermeer", "c. 1665"),
    ("the-kiss",      "The Kiss",                "Gustav Klimt",      "1908"),
    ("water-lilies",  "Water Lilies",            "Claude Monet",      "1906"),
]
target = COLS / ROWS
out = []
for pid, title, artist, year in META:
    im = Image.open(f"/tmp/mosaic/{pid}.jpg").convert("RGB")
    w, h = im.size
    ar = w / h
    if ar > target:  # too wide -> crop width
        nw = int(h * target); x0 = (w - nw) // 2; im = im.crop((x0, 0, x0 + nw, h))
    else:            # too tall -> crop height
        nh = int(w / target); y0 = (h - nh) // 2; im = im.crop((0, y0, w, y0 + nh))
    im = im.resize((COLS, ROWS), Image.LANCZOS)
    raw = im.tobytes()
    assert len(raw) == COLS * ROWS * 3
    out.append((pid, title, artist, year, base64.b64encode(raw).decode()))

with open("/home/sandbox/nativelet/packages/ui/src/components/mosaic-gallery/mosaic-data.ts", "w") as f:
    f.write("// GENERATED by scripts/build-mosaic-data.py - do not edit by hand.\n")
    f.write("// Cell colors (RGB888, row-major) averaged from public-domain paintings\n")
    f.write("// sourced from Wikimedia Commons. See component README for attributions.\n\n")
    f.write(f"export const MOSAIC_COLS = {COLS};\nexport const MOSAIC_ROWS = {ROWS};\n\n")
    f.write("export interface MosaicPainting {\n  id: string;\n  title: string;\n  artist: string;\n  year: string;\n  /** Base64 RGB888, COLS*ROWS*3 bytes, row-major. */\n  colorsB64: string;\n}\n\n")
    f.write("export const MOSAIC_PAINTINGS: MosaicPainting[] = [\n")
    for pid, title, artist, year, b64 in out:
        f.write("  {\n")
        f.write(f"    id: '{pid}',\n    title: '{title}',\n    artist: '{artist}',\n    year: '{year}',\n")
        f.write(f"    colorsB64:\n")
        for i in range(0, len(b64), 100):
            f.write(f"      '{b64[i:i+100]}' +\n")
        f.write("      '',\n  },\n")
    f.write("];\n")
print("cells:", COLS*ROWS, "paintings:", len(out))
